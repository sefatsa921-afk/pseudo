import { existsSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..');
const envPath = resolve(projectRoot, 'backend', '.env');
const output = resolve(projectRoot, 'www', 'supabase-config.js');

function parseEnv(text) {
  return text.split(/\r?\n/).reduce((values, line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return values;
    const separator = trimmed.indexOf('=');
    if (separator < 1) return values;
    const key = trimmed.slice(0, separator).trim();
    const value = trimmed.slice(separator + 1).trim().replace(/^['"]|['"]$/g, '');
    values[key] = value;
    return values;
  }, {});
}

const fileValues = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};
const url = process.env.SUPABASE_URL || fileValues.SUPABASE_URL || '';
const publishableKey = process.env.SUPABASE_PUBLISHABLE_KEY || fileValues.SUPABASE_PUBLISHABLE_KEY || process.env.SUPABASE_ANON_KEY || fileValues.SUPABASE_ANON_KEY || '';
const config = { enabled: Boolean(url && publishableKey), url, publishableKey };

// Safety: if no env values were supplied but www/supabase-config.js already holds a working config,
// keep it instead of overwriting it with the disabled placeholder.
if (!config.enabled && existsSync(output) && /enabled:\s*true/.test(readFileSync(output, 'utf8'))) {
  console.log(`Kept existing ${output} (no SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY supplied)`);
  process.exit(0);
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `// Generated by scripts/write-supabase-config.mjs (public settings only; demo mode when disabled).\n// Never put a secret or service-role key here: this file ships inside the APK.\nwindow.VEYA_SUPABASE_CONFIG = ${JSON.stringify(config)};\n`);
console.log(`Wrote ${output} (${config.enabled ? 'backend configured' : 'demo fallback'})`);
